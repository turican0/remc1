#include "test_support.h"

#include <cstdio>
#include <fstream>
#include <sstream>

#ifndef REMC1_GOLDENS_DIR
#error "REMC1_GOLDENS_DIR must be defined by the build"
#endif

namespace remc1test {

std::string HashHex(uint64_t h)
{
	char buf[17];
	snprintf(buf, sizeof(buf), "%016llx", (unsigned long long)h);
	return buf;
}

std::string DataDir()
{
	const char* env = std::getenv("REMC1_DATA_DIR");
	if (!env || !*env)
		return {};
	std::error_code ec;
	if (!std::filesystem::is_directory(std::filesystem::path(env) / "CD", ec))
		return {};
	return env;
}

std::vector<uint8_t> ReadFile(const std::filesystem::path& p)
{
	std::ifstream in(p, std::ios::binary);
	return std::vector<uint8_t>((std::istreambuf_iterator<char>(in)), std::istreambuf_iterator<char>());
}

Goldens::Goldens(const std::string& name)
	: path_(std::filesystem::path(REMC1_GOLDENS_DIR) / name)
{
	const char* upd = std::getenv("REMC1_UPDATE_GOLDENS");
	updating_ = upd && *upd && *upd != '0';
	std::ifstream in(path_);
	std::string line;
	while (std::getline(in, line)) {
		if (line.empty() || line[0] == '#')
			continue;
		auto sp = line.find(' ');
		if (sp != std::string::npos)
			values_[line.substr(0, sp)] = line.substr(sp + 1);
	}
}

Goldens::~Goldens()
{
	if (!updating_ || !dirty_)
		return;
	std::ofstream out(path_, std::ios::binary);
	out << "# generated by remc1-tests with REMC1_UPDATE_GOLDENS=1\n";
	for (auto& kv : values_)
		out << kv.first << ' ' << kv.second << '\n';
}

bool Goldens::Check(const std::string& key, const std::string& value, std::string* expected)
{
	auto it = values_.find(key);
	if (updating_) {
		if (it == values_.end() || it->second != value) {
			values_[key] = value;
			dirty_ = true;
		}
		return true;
	}
	if (expected)
		*expected = it == values_.end() ? std::string("<missing>") : it->second;
	return it != values_.end() && it->second == value;
}

} // namespace remc1test
