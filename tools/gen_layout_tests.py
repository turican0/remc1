#!/usr/bin/env python3
"""Generate struct-layout tests from engine/Basic.h (and sub_main.h).

The decompiled structs document the original DOS layout in two ways:
  * a `// len N` (or `//lenght N`) comment on the struct  -> sizeof(T) == N
  * fields named `..._<off>` that also carry a `//<off>` comment -> offsetof(T, field) == off
Only facts stated twice (name suffix == comment) are trusted for offsets.

These tests pin the 32-bit DOS layout. In the 64-bit port (Phase 5) structs containing pointers
will change size; their DOS layout must then be preserved by "shadow" structs / serializers, and
these tests are moved to the shadow types.

Usage: python tools/gen_layout_tests.py  (writes tests/generated/layout_cases.inc)
"""
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SOURCES = ["engine/Basic.h", "sub_main.h"]
OUT = os.path.join(ROOT, "tests", "generated", "layout_cases.inc")


def strip_block_comments(s):
    return re.sub(r"/\*.*?\*/", lambda m: "\n" * m.group(0).count("\n"), s, flags=re.S)


def structs(text):
    """Yield (name, header_comment, body) for `typedef struct [tag] { ... } Name;` (nested braces ok)."""
    for m in re.finditer(r"typedef\s+(?:struct|union)\s*\w*\s*\{([^\n]*)", text):
        start = m.end(0) - len(m.group(1))
        depth, i = 1, start
        while depth and i < len(text):
            if text[i] == "{":
                depth += 1
            elif text[i] == "}":
                depth -= 1
            i += 1
        body = text[start:i - 1]
        nm = re.match(r"\s*(\w+)\s*;", text[i:])
        if nm:
            yield nm.group(1), m.group(1), body, text.startswith("typedef union", m.start())


def top_level_lines(body):
    depth = 0
    for line in body.split("\n"):
        if depth == 0:
            yield line
        depth += line.count("{") - line.count("}")


def main():
    global name_facts
    name_facts = []  # (struct, field, offset-from-name) for fields whose only evidence is the name
    cases = []
    seen = set()
    for src in SOURCES:
        text = strip_block_comments(open(os.path.join(ROOT, src), encoding="latin-1").read())
        for name, header, body, is_union in structs(text):
            if name in seen:
                continue
            seen.add(name)
            m = re.search(r"len(?:ght|gth)?\s*[:=]?\s*(\d+)", header, re.I)
            if m:
                cases.append(f"LAYOUT_SIZE({name}, {m.group(1)})  // {src}")
            if is_union:
                continue
            facts = []
            first_field_off = None
            for line in top_level_lines(body):
                if first_field_off is None and re.match(r"\s*[\w:]+[\s*]+\w+\s*(?:\[[^\]]*\])*\s*;", line):
                    c = re.search(r";\s*//\s*(\d+)\b", line)
                    first_field_off = int(c.group(1)) if c else 0
                nm = re.match(r"\s*[\w:]+(?:\s+[\w:]+)*?[\s*]+(\w+)\s*(?:\[[^\]]*\])*\s*;", line)
                if nm:
                    sfx = re.search(r"_(\d+)$", nm.group(1))
                    if sfx and not re.search(r";\s*//\s*\d", line):
                        name_facts.append((name, nm.group(1), int(sfx.group(1))))
                fm = re.match(r"\s*[\w:]+(?:\s+[\w:]+)*?[\s*]+(\w+)\s*(?:\[[^\]]*\])*\s*;\s*//\s*(\d+)\b", line)
                if not fm:
                    continue
                field, off = fm.group(1), fm.group(2)
                suffix = re.search(r"_(\d+)$", field)
                if suffix and suffix.group(1) == off:
                    facts.append((field, int(off)))
            # Embedded sub-structs (e.g. Type_29885_90 inside the entity at +90) document offsets
            # relative to the parent: rebase on the first field's offset.
            base = first_field_off or 0
            for field, off in facts:
                cases.append(f"LAYOUT_OFFSET({name}, {field}, {off - base})")
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w", newline="\n") as f:
        f.write("// GENERATED by tools/gen_layout_tests.py from engine/Basic.h + sub_main.h - do not edit.\n")
        f.write("// Original DOS (32-bit) layout facts stated in the decompiled headers.\n")
        for c in cases:
            f.write(c + "\n")
    print(f"{len(cases)} layout cases -> {os.path.relpath(OUT, ROOT)}")
    # Weaker evidence: offsets implied only by field names (var_50, u16_327, ...). Not a test by
    # default - names can lie - but a mismatch is worth a look (see --check-names in the guide).
    out2 = os.path.join(os.path.dirname(OUT), "layout_name_cases.inc")
    with open(out2, "w", newline="\n") as f:
        f.write("// GENERATED by tools/gen_layout_tests.py - offsets implied by field names only.\n")
        for s, fld, off in name_facts:
            f.write(f"LAYOUT_NAME_OFFSET({s}, {fld}, {off})\n")
    print(f"{len(name_facts)} name-implied offsets -> {os.path.relpath(out2, ROOT)}")


if __name__ == "__main__":
    main()
